# Copied from samples/ios/certs/gen.sh, with two changes: the server certificate also names 10.0.2.2 (the host as an
# Android emulator reaches it), and the output is split: the CA (all the app needs) goes to composeApp, the server chain
# and key to the demo server.
# Generates the demo's private PKI (a P-256 CA and a server certificate for kuicksilver.local, localhost, 127.0.0.1, ::1
# and 10.0.2.2, 100-year validity) and writes it as PEM strings into DemoCerts.kt and DemoServerCerts.kt. Test material
# only: the key is public. Requires an OpenSSL 3.x CLI (OPENSSL=... picks one). Usage: certs/gen.sh
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
app="$here/../composeApp/src/commonMain/kotlin/io/kuicksilver/sample/compose/DemoCerts.kt"
srv="$here/../server/src/main/kotlin/io/kuicksilver/sample/compose/server/DemoServerCerts.kt"
O="${OPENSSL:-$(command -v openssl)}"; "$O" version | grep -q 'OpenSSL 3' || { echo "need an OpenSSL 3.x CLI" >&2; exit 2; }
work=$(mktemp -d); trap 'rm -rf "$work"' EXIT INT TERM HUP; cd "$work"
"$O" req -x509 -newkey ec -pkeyopt ec_paramgen_curve:P-256 -nodes -keyout ca.key -out ca.pem -days 36500 -subj "/CN=Kuicksilver Compose Demo CA" \
  -addext "basicConstraints=critical,CA:TRUE" -addext "keyUsage=critical,keyCertSign" 2>/dev/null
"$O" ecparam -name prime256v1 -genkey -noout -out server.ec
"$O" pkcs8 -topk8 -nocrypt -in server.ec -out server.key
"$O" req -new -key server.key -out server.csr -subj "/CN=kuicksilver.local" 2>/dev/null
printf 'basicConstraints=CA:FALSE\nkeyUsage=digitalSignature\nextendedKeyUsage=serverAuth\nsubjectAltName=DNS:kuicksilver.local,DNS:localhost,IP:127.0.0.1,IP:::1,IP:10.0.2.2\n' > server.ext
"$O" x509 -req -in server.csr -CA ca.pem -CAkey ca.key -CAcreateserial -out server.pem -days 36500 -extfile server.ext 2>/dev/null
{
  printf '%s\n' '// Copyright 2026 The Kuicksilver Authors' '// SPDX-License-Identifier: Apache-2.0' '// generated by certs/gen.sh — do not edit' \
    'package io.kuicksilver.sample.compose' '' \
    '/** The CA of the demo'"'"'s private PKI as PEM text, as an application would read it from a file. */' \
    'object DemoCerts {'
  printf '    /** The CA every client of the demo trusts for the demo server (and nothing else). */\n    val caPem: String = """\n%s"""\n}\n' "$(cat ca.pem)"
} > "$app"
{
  printf '%s\n' '// Copyright 2026 The Kuicksilver Authors' '// SPDX-License-Identifier: Apache-2.0' '// generated by certs/gen.sh — do not edit' \
    'package io.kuicksilver.sample.compose.server' '' \
    '/** The demo server'"'"'s certificate and key as PEM text. Test material: the key is public. */' \
    'object DemoServerCerts {'
  printf '    /** The chain, leaf first: kuicksilver.local, localhost, 127.0.0.1, ::1, 10.0.2.2. */\n    val chainPem: String = """\n%s"""\n\n' "$(cat server.pem)"
  printf '    /** The PKCS#8 key. */\n    val keyPem: String = """\n%s"""\n}\n' "$(cat server.key)"
} > "$srv"
echo "wrote $app and $srv"
