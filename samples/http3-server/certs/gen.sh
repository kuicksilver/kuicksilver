# A private CA and a server certificate for localhost, 127.0.0.1 and ::1 (P-256), for running the sample by hand:
#   certs/gen.sh          writes build/dev-certs/ca.pem, chain.pem and key.pem (valid 30 days; application.conf reads them)
#   certs/gen.sh --test   writes the tests' TestCerts.kt instead (100 years; public test material)
# Requires an OpenSSL 3 or 4 CLI (OPENSSL=... picks one). Never use either pair outside your own machine.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
mode="${1:-dev}"
case "$mode" in dev) days=30 ;; --test) days=36500 ;; *) echo "usage: certs/gen.sh [--test]" >&2; exit 2 ;; esac
O="${OPENSSL:-$(command -v openssl)}"; "$O" version | grep -q '^OpenSSL [34]\.' || { echo "need an OpenSSL 3 or 4 CLI (OPENSSL=...)" >&2; exit 2; }
work=$(mktemp -d); trap 'rm -rf "$work"' EXIT INT TERM HUP; cd "$work"
"$O" req -x509 -newkey ec -pkeyopt ec_paramgen_curve:P-256 -nodes -keyout ca.key -out ca.pem -days "$days" -subj "/CN=HTTP3 Sample CA" \
  -addext "basicConstraints=critical,CA:TRUE" -addext "keyUsage=critical,keyCertSign" 2>/dev/null
"$O" ecparam -name prime256v1 -genkey -noout -out server.ec
"$O" pkcs8 -topk8 -nocrypt -in server.ec -out key.pem
"$O" req -new -key key.pem -out server.csr -subj "/CN=localhost" 2>/dev/null
printf 'basicConstraints=CA:FALSE\nkeyUsage=digitalSignature\nextendedKeyUsage=serverAuth\nsubjectAltName=DNS:localhost,IP:127.0.0.1,IP:::1\n' > server.ext
"$O" x509 -req -in server.csr -CA ca.pem -CAkey ca.key -CAcreateserial -out chain.pem -days "$days" -extfile server.ext 2>/dev/null
if [ "$mode" = dev ]; then
  mkdir -p "$here/../build/dev-certs"; out="$(cd "$here/../build/dev-certs" && pwd)"
  cp ca.pem chain.pem "$out/"; (umask 077; cp key.pem "$out/key.pem")
  echo "wrote $out/{ca,chain,key}.pem: curl --cacert $out/ca.pem ..."
  exit 0
fi
out="$here/../src/test/kotlin/io/kuicksilver/sample/http3/TestCerts.kt"
{
  printf '%s\n' '// Copyright 2026 The Kuicksilver Authors' '// SPDX-License-Identifier: Apache-2.0' '// generated by certs/gen.sh --test — do not edit' \
    'package io.kuicksilver.sample.http3' '' \
    '/** The tests'"'"' private PKI as PEM text; the tests write it to files for application.conf. Test material: the key is public. */' \
    'object TestCerts {'
  printf '    /** The CA the test clients trust. */\n    val caPem: String = """\n%s"""\n\n' "$(cat ca.pem)"
  printf '    /** The server chain: localhost, 127.0.0.1, ::1. */\n    val chainPem: String = """\n%s"""\n\n' "$(cat chain.pem)"
  printf '    /** The server'"'"'s PKCS#8 key. */\n    val keyPem: String = """\n%s"""\n}\n' "$(cat key.pem)"
} > "$out"
echo "wrote $out"
