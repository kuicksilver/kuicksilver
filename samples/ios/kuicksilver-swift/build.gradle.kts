import java.security.MessageDigest
import org.jetbrains.kotlin.gradle.plugin.mpp.apple.XCFramework

plugins {
    kotlin("multiplatform")
}

val kuicksilver = providers.gradleProperty("kuicksilver.version").getOrElse("0.3.0-SNAPSHOT")
// The checkout the release is built in: the dSYMs name the sources relative to it, so the zip does not depend on (or
// reveal) where the checkout is, and its SwiftPM checksum is the same in every checkout (tools/release/xcframework.sh).
val repositoryRoot: String = rootProject.projectDir.resolve("../..").canonicalPath

// Kuicksilver.xcframework for Swift-only applications (docs/guide/ios.md, "Swift-only"): a dynamic framework, so each
// slice carries its own dSYM and its own PrivacyInfo.xcprivacy, distributed as a SwiftPM binaryTarget.
//   ./gradlew -p samples/ios :kuicksilver-swift:assembleKuicksilverReleaseXCFramework
//   -> kuicksilver-swift/build/XCFrameworks/release/Kuicksilver.xcframework (+ Kuicksilver.framework.dSYM per slice)
//   ./gradlew -p samples/ios :kuicksilver-swift:zipKuicksilverXCFramework   (the zip and checksum SwiftPM needs)
// KuicksilverInfo.VERSION is the version the framework is built as (-Pkuicksilver.version), not a fallback in the source.
val generateKuicksilverInfo = tasks.register("generateKuicksilverInfo") {
    val dir = layout.buildDirectory.dir("generated/kuicksilverInfo")
    val version = kuicksilver
    inputs.property("version", version)
    outputs.dir(dir)
    doLast {
        val file = dir.get().file("io/kuicksilver/swift/KuicksilverInfo.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |// Generated by samples/ios/kuicksilver-swift/build.gradle.kts (generateKuicksilverInfo); do not edit.
            |package io.kuicksilver.swift
            |
            |/**
            | * The umbrella of Kuicksilver.xcframework. It adds no API of its own: the framework exports the public API of
            | * kuicksilver-tls, kuicksilver-quic and kuicksilver-http3, and Swift calls their suspend functions as `async`
            | * methods (or with completion handlers). This object only names the build so a Swift app can log what it ships.
            | */
            |public object KuicksilverInfo {
            |    /** The Kuicksilver version this framework was built from. */
            |    public const val VERSION: String = "$version"
            |}
            |""".trimMargin(),
        )
    }
}

kotlin {
    val xcf = XCFramework("Kuicksilver")
    listOf(iosArm64(), iosSimulatorArm64()).forEach { target ->
        target.binaries.framework {
            baseName = "Kuicksilver"
            isStatic = false
            // the public API of these modules is visible from Swift; everything else they use stays internal
            export("io.kuicksilver:kuicksilver-tls:$kuicksilver")
            export("io.kuicksilver:kuicksilver-quic:$kuicksilver")
            export("io.kuicksilver:kuicksilver-http3:$kuicksilver")
            binaryOption("bundleId", "io.kuicksilver.Kuicksilver")
            binaryOption("bundleShortVersionString", kuicksilver.substringBefore('-'))
            freeCompilerArgs += "-Xdebug-prefix-map=$repositoryRoot=."
            xcf.add(this)
        }
    }
    sourceSets {
        commonMain.get().kotlin.srcDir(generateKuicksilverInfo)
        commonMain.dependencies {
            api("io.kuicksilver:kuicksilver-tls:$kuicksilver")
            api("io.kuicksilver:kuicksilver-quic:$kuicksilver")
            api("io.kuicksilver:kuicksilver-http3:$kuicksilver")
        }
    }
}

// Apple reads a framework's privacy manifest from the framework bundle (the root of a shallow iOS bundle). The licences
// travel with the framework into every app that embeds it: Kuicksilver's LICENSE and NOTICE, and the licence of the
// OpenSSL linked into it, at the path NOTICE names (licenses/LICENSE.openssl.txt).
val privacyManifest = rootProject.file("../../kuicksilver-native/apple/PrivacyInfo.xcprivacy")
val licenceFiles = mapOf(
    "LICENSE" to rootProject.file("../../LICENSE"),
    "NOTICE" to rootProject.file("../../NOTICE"),
    "licenses/LICENSE.openssl.txt" to rootProject.file("../../licenses/LICENSE.openssl.txt"),
)
tasks.matching { it.name.startsWith("assembleKuicksilver") && it.name.endsWith("XCFramework") }.configureEach {
    inputs.file(privacyManifest)
    inputs.files(licenceFiles.values)
    doLast {
        outputs.files.files.flatMap { it.walkTopDown().filter { f -> f.isDirectory && f.name == "Kuicksilver.framework" }.toList() }
            .forEach { framework ->
                privacyManifest.copyTo(framework.resolve("PrivacyInfo.xcprivacy"), overwrite = true)
                licenceFiles.forEach { (path, file) -> file.copyTo(framework.resolve(path), overwrite = true) }
            }
        // dsymutil records the absolute path of the linked binary in each dSYM; name it relative to the repository
        outputs.files.files.flatMap { it.walkTopDown().filter { f -> f.isFile && f.extension == "yml" && f.path.contains(".dSYM/") }.toList() }
            .forEach { it.writeText(it.readText().replace("$repositoryRoot/", "")) }
        // xcodebuild -create-xcframework lists the slices in no fixed order; sort them so the zip's checksum is stable
        val plists = outputs.files.files.flatMap { it.walkTopDown().filter { f -> f.name == "Info.plist" && f.parentFile.name == "Kuicksilver.xcframework" }.toList() }
        check(plists.isNotEmpty()) { "no Kuicksilver.xcframework/Info.plist in ${outputs.files.files}" }
        plists.forEach { sortSlices(it) }
    }
}

fun sortSlices(plist: File) {
    val factory = javax.xml.parsers.DocumentBuilderFactory.newInstance()
    factory.setFeature("http://apache.org/xml/features/nonvalidating/load-external-dtd", false)
    val doc = factory.newDocumentBuilder().parse(plist)
    fun org.w3c.dom.Node.elements() = (0 until childNodes.length).map { childNodes.item(it) }.filterIsInstance<org.w3c.dom.Element>()
    fun org.w3c.dom.Element.valueOf(key: String) = elements().zipWithNext().firstOrNull { (k, _) -> k.tagName == "key" && k.textContent == key }?.second
    val top = doc.documentElement.elements().single { it.tagName == "dict" }
    val slices = top.valueOf("AvailableLibraries") ?: error("$plist: no AvailableLibraries")
    val sorted = slices.elements().sortedBy { it.valueOf("LibraryIdentifier")?.textContent ?: error("$plist: a slice without LibraryIdentifier") }
    sorted.forEach { slices.removeChild(it) }
    sorted.forEach { slices.appendChild(it) }
    javax.xml.transform.TransformerFactory.newInstance().newTransformer()
        .transform(javax.xml.transform.dom.DOMSource(doc), javax.xml.transform.stream.StreamResult(plist))
    // back to the layout Apple's tools write
    val plutil = ProcessBuilder("plutil", "-convert", "xml1", plist.path).inheritIO().start()
    check(plutil.waitFor() == 0) { "plutil -convert xml1 $plist failed" }
}

// SwiftPM's binaryTarget takes a zip and its checksum (`swift package compute-checksum` gives the same SHA-256).
tasks.register<Zip>("zipKuicksilverXCFramework") {
    dependsOn("assembleKuicksilverReleaseXCFramework")
    from(layout.buildDirectory.dir("XCFrameworks/release")) { include("Kuicksilver.xcframework/**") }
    archiveFileName.set("Kuicksilver.xcframework.zip")
    destinationDirectory.set(layout.buildDirectory.dir("spm"))
    isPreserveFileTimestamps = false; isReproducibleFileOrder = true
    // the same modes on every machine (a umask must not change the checksum): executables 755, everything else 644
    dirPermissions { unix("755") }
    eachFile { permissions { unix(if (file.canExecute()) "755" else "644") } }
    doLast {
        val zip = archiveFile.get().asFile
        val sha = MessageDigest.getInstance("SHA-256").digest(zip.readBytes()).joinToString("") { "%02x".format(it) }
        zip.resolveSibling("checksum.txt").writeText("$sha\n")
        logger.lifecycle("SwiftPM binaryTarget checksum: $sha")
    }
}
