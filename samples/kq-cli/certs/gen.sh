# Generates the sample's private PKI (a P-256 CA and a server certificate for localhost, 127.0.0.1 and ::1, 100-year
# validity) and writes it as PEM strings into the test source set's SampleCerts.kt. Test material only: the key is public.
# Requires an OpenSSL 3.x or 4.x CLI. Usage: certs/gen.sh
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
out="$here/../src/commonTest/kotlin/io/kuicksilver/sample/kq/SampleCerts.kt"
O="${OPENSSL:-$(command -v openssl)}"; "$O" version | grep -q 'OpenSSL [34]\.' || { echo "need an OpenSSL 3.x or 4.x CLI" >&2; exit 2; }
work=$(mktemp -d); trap 'rm -rf "$work"' EXIT INT TERM HUP; cd "$work"
"$O" req -x509 -newkey ec -pkeyopt ec_paramgen_curve:P-256 -nodes -keyout ca.key -out ca.pem -days 36500 -subj "/CN=kq Sample CA" \
  -addext "basicConstraints=critical,CA:TRUE" -addext "keyUsage=critical,keyCertSign" 2>/dev/null
"$O" ecparam -name prime256v1 -genkey -noout -out server.ec
"$O" pkcs8 -topk8 -nocrypt -in server.ec -out server.key
"$O" req -new -key server.key -out server.csr -subj "/CN=localhost" 2>/dev/null
printf 'basicConstraints=CA:FALSE\nkeyUsage=digitalSignature\nextendedKeyUsage=serverAuth\nsubjectAltName=DNS:localhost,IP:127.0.0.1,IP:::1\n' > server.ext
"$O" x509 -req -in server.csr -CA ca.pem -CAkey ca.key -CAcreateserial -out server.pem -days 36500 -extfile server.ext 2>/dev/null
{
  printf '%s\n' '// Copyright 2026 The Kuicksilver Authors' '// SPDX-License-Identifier: Apache-2.0' '// generated by certs/gen.sh — do not edit' \
    'package io.kuicksilver.sample.kq' '' \
    '/** The test server'"'"'s private PKI as PEM text. Test material: the server key is public, and none of it is in the kq executable. */' \
    'object SampleCerts {'
  printf '    /** The CA kq trusts with --cacert. */\n    val caPem: String = """\n%s"""\n\n' "$(cat ca.pem)"
  printf '    /** The server chain, leaf first: localhost, 127.0.0.1, ::1. */\n    val serverChainPem: String = """\n%s"""\n\n' "$(cat server.pem)"
  printf '    /** The server'"'"'s PKCS#8 key. */\n    val serverKeyPem: String = """\n%s"""\n}\n' "$(cat server.key)"
} > "$out"
echo "wrote $out"
