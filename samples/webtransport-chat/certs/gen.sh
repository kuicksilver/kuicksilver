# Generates the sample's private PKI (a P-256 CA and a server certificate for chat.test, localhost, 127.0.0.1 and ::1,
# 100-year validity) and writes it as PEM strings: the CA into SampleCa.kt (common code, what clients trust), the server's
# chain and key into SampleServerPem.kt (JVM only). Test material only: the key is public.
# Requires an OpenSSL 3 or 4 CLI (OPENSSL=... picks one). Usage: certs/gen.sh
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
common="$here/../src/commonMain/kotlin/io/kuicksilver/sample/chat/SampleCa.kt"
jvm="$here/../src/jvmMain/kotlin/io/kuicksilver/sample/chat/SampleServerPem.kt"
O="${OPENSSL:-$(command -v openssl)}"; "$O" version | grep -q '^OpenSSL [34]\.' || { echo "need an OpenSSL 3 or 4 CLI" >&2; exit 2; }
work=$(mktemp -d); trap 'rm -rf "$work"' EXIT INT TERM HUP; cd "$work"
"$O" req -x509 -newkey ec -pkeyopt ec_paramgen_curve:P-256 -nodes -keyout ca.key -out ca.pem -days 36500 -subj "/CN=Chat Sample CA" \
  -addext "basicConstraints=critical,CA:TRUE" -addext "keyUsage=critical,keyCertSign" 2>/dev/null
"$O" ecparam -name prime256v1 -genkey -noout -out server.ec
"$O" pkcs8 -topk8 -nocrypt -in server.ec -out server.key
"$O" req -new -key server.key -out server.csr -subj "/CN=chat.test" 2>/dev/null
printf 'basicConstraints=CA:FALSE\nkeyUsage=digitalSignature\nextendedKeyUsage=serverAuth\nsubjectAltName=DNS:chat.test,DNS:localhost,IP:127.0.0.1,IP:::1\n' > server.ext
"$O" x509 -req -in server.csr -CA ca.pem -CAkey ca.key -CAcreateserial -out server.pem -days 36500 -extfile server.ext 2>/dev/null
# the CA goes to common code (every client trusts it); the server's chain and key to JVM code only, so that no
# common-code, iOS or macOS build carries them
{
  printf '%s\n' '// Copyright 2026 The Kuicksilver Authors' '// SPDX-License-Identifier: Apache-2.0' '// generated by certs/gen.sh — do not edit' \
    'package io.kuicksilver.sample.chat' '' \
    '/** The sample'"'"'s private CA as PEM text: what a client trusts (TrustConfig.AnchoredCa). Public, and only a certificate. */' \
    'object SampleCa {'
  printf '    /** The CA certificate. */\n    val caPem: String = """\n%s"""\n}\n' "$(cat ca.pem)"
} > "$common"
{
  printf '%s\n' '// Copyright 2026 The Kuicksilver Authors' '// SPDX-License-Identifier: Apache-2.0' '// generated by certs/gen.sh — do not edit' \
    'package io.kuicksilver.sample.chat' '' \
    '/**' \
    ' * The sample server'"'"'s certificate and key, signed by [SampleCa]: the command line server'"'"'s fallback on loopback, and the' \
    ' * tests'"'"'. Test material: the key is public. JVM code only, so that no common-code, iOS or macOS build carries it.' \
    ' */' \
    'object SampleServerPem {'
  printf '    /** The server chain, leaf first: chat.test, localhost, 127.0.0.1, ::1. */\n    val chainPem: String = """\n%s"""\n\n' "$(cat server.pem)"
  printf '    /** The server'"'"'s PKCS#8 key. */\n    val keyPem: String = """\n%s"""\n}\n' "$(cat server.key)"
} > "$jvm"
echo "wrote $common and $jvm"
