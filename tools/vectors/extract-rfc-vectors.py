"""Extracts the RFC 9001 / RFC 9369 Appendix A test vectors from the RFC text into C headers.
Usage: extract-rfc-vectors.py <rfc9001.txt> <rfc9369.txt> <out dir>
       extract-rfc-vectors.py <rfc9001.txt> <rfc9369.txt> --kotlin <out.kt> [<package>]   (packet vectors for Kotlin tests)"""
import re, sys, os

def sections(text, names):
    idx = [(n, text.index("\n" + n + "  ")) for n in names]
    idx.append(("END", text.index("\nAppendix B.") if "\nAppendix B." in text else text.index("\nAcknowledgments")))
    return {idx[i][0]: text[idx[i][1]:idx[i + 1][1]] for i in range(len(names))}

HEX = re.compile(r"^[0-9a-f ]+$")
def blocks(sec):
    out, cur = [], ""
    for raw in sec.split("\n"):
        line = raw.strip()
        m = re.match(r"^([A-Za-z0-9_ ]+?)\s*[=:]\s*([0-9a-f]{8,})$", line)
        if m: 
            if cur: out.append(cur); cur = ""
            out.append(m.group(2)); continue
        if line.startswith("= "): line = line[2:].strip()
        if (len(line) >= 8 or (cur and len(line) >= 2)) and HEX.match(line) and "Page" not in raw and not raw.startswith("RFC "):
            cur += line.replace(" ", "")
        else:
            if cur: out.append(cur); cur = ""
    if cur: out.append(cur)
    return [bytes.fromhex(b) for b in out]

def arr(name, b):
    return "static const uint8_t %s[%d] = {%s};\n" % (name, len(b), ",".join("0x%02x" % x for x in b))

def parse(path):
    """Named Appendix A vectors of one RFC, in header order."""
    text = open(path).read()
    s = sections(text, ["A.1.", "A.2.", "A.3.", "A.4.", "A.5."])
    a1 = [b for b in blocks(s["A.1."]) if len(b) in (12, 16, 32)]
    # order in both RFCs: initial_secret(32) client_initial_secret(32) key iv hp server_initial_secret(32) key iv hp
    assert [len(b) for b in a1] == [32, 32, 16, 12, 16, 32, 16, 12, 16], [len(b) for b in a1]
    a2 = blocks(s["A.2."]); a2_big = [b for b in a2 if len(b) > 100]
    crypto, protected = a2_big[0], a2_big[-1]
    a2_small = [b for b in a2 if len(b) <= 100]
    header, sample, mask, pheader = [b for b in a2_small if len(b) == 22][0], [b for b in a2_small if len(b) == 16][0], [b for b in a2_small if len(b) == 5][0], [b for b in a2_small if len(b) == 22][1]
    assert len(protected) == 1200
    a3 = blocks(s["A.3."]); a3_big = sorted([b for b in a3 if len(b) > 50], key=len)
    payload, protected3 = a3_big[0], a3_big[-1]
    h3 = [b for b in a3 if len(b) == 20]; s3 = [b for b in a3 if len(b) == 16][0]; m3 = [b for b in a3 if len(b) == 5][0]
    a4 = [b for b in blocks(s["A.4."]) if len(b) == 36][0]
    a5 = blocks(s["A.5."])
    secret, key, iv, hp, ku = [b for b in a5 if len(b) == 32][:5] if len([b for b in a5 if len(b) == 32]) >= 5 else (None,)*5
    iv = [b for b in a5 if len(b) == 12][0]
    s32 = [b for b in a5 if len(b) == 32]; secret, key, hp, ku = s32[0], s32[1], s32[2], s32[3]
    nonce = [b for b in a5 if len(b) == 12][1]; uhdr = [b for b in a5 if len(b) == 4][0]; ct = [b for b in a5 if len(b) == 17][0]
    sample5 = [b for b in a5 if len(b) == 16][0]; mask5 = [b for b in a5 if len(b) == 5][0]; phdr5 = [b for b in a5 if len(b) == 4][1]; pkt = [b for b in a5 if len(b) == 21][0]
    v = [("DCID", bytes.fromhex("8394c8f03e515708"))]
    v += list(zip(["INITIAL_SECRET", "CLIENT_SECRET", "CLIENT_KEY", "CLIENT_IV", "CLIENT_HP", "SERVER_SECRET", "SERVER_KEY", "SERVER_IV", "SERVER_HP"], a1))
    v += [("A2_CRYPTO", crypto), ("A2_HEADER", header), ("A2_SAMPLE", sample), ("A2_MASK", mask), ("A2_PROTECTED_HEADER", pheader), ("A2_PROTECTED", protected),
          ("A3_PAYLOAD", payload), ("A3_HEADER", h3[0]), ("A3_SAMPLE", s3), ("A3_MASK", m3), ("A3_PROTECTED_HEADER", h3[1]), ("A3_PROTECTED", protected3), ("A4_RETRY", a4),
          ("A5_SECRET", secret), ("A5_KEY", key), ("A5_IV", iv), ("A5_HP", hp), ("A5_KU", ku), ("A5_NONCE", nonce), ("A5_HEADER", uhdr), ("A5_CIPHERTEXT", ct), ("A5_SAMPLE", sample5), ("A5_MASK", mask5), ("A5_PROTECTED_HEADER", phdr5), ("A5_PACKET", pkt)]
    return v

def extract(path, tag, version_label):
    o = "/* %s Appendix A vectors, generated by tools/vectors/extract-rfc-vectors.py from %s. Do not edit. */\n" % (tag, os.path.basename(path))
    o += "/* Copyright 2026 The Kuicksilver Authors */\n/* SPDX-License-Identifier: Apache-2.0 */\n#ifndef VECTORS_%s_H\n#define VECTORS_%s_H\n#include <stdint.h>\n" % (tag, tag)
    o += "#define %s_VERSION %s\n" % (tag, version_label)
    for n, b in parse(path): o += arr(tag + "_" + n, b)
    o += "#define %s_A2_PN 2\n#define %s_A3_PN 1\n#define %s_A5_PN 654360564ULL\n#endif\n" % (tag, tag, tag)
    return o

PACKET_NAMES = ["DCID", "A2_CRYPTO", "A2_HEADER", "A2_SAMPLE", "A2_MASK", "A2_PROTECTED", "A3_PAYLOAD", "A3_HEADER", "A3_SAMPLE", "A3_MASK", "A3_PROTECTED", "A4_RETRY"]
def kotlin_object(path, name, version):
    o = "internal object %s {\n    const val VERSION: Int = %s\n    const val A2_PN: Long = 2L; const val A3_PN: Long = 1L\n" % (name, version)
    o += "    val A3_SCID: ByteArray = byteArrayOf(%s)\n" % ", ".join("0x%02x.toByte()" % x for x in bytes.fromhex("f067a5502a4262b5"))
    for n, b in parse(path):
        if n in PACKET_NAMES: o += "    val %s: ByteArray = byteArrayOf(%s)\n" % (n, ", ".join("0x%02x.toByte()" % x for x in b))
    return o + "}\n"

if "--kotlin" in sys.argv:
    k = sys.argv.index("--kotlin"); pkg = sys.argv[k + 2] if len(sys.argv) > k + 2 else "io.kuicksilver.quic"
    o = "// Copyright 2026 The Kuicksilver Authors\n// SPDX-License-Identifier: Apache-2.0\n// generated by tools/vectors/extract-rfc-vectors.py --kotlin - do not edit\n@file:Suppress(\"ktlint\", \"MaxLineLength\")\n\npackage %s\n\n" % pkg
    o += kotlin_object(sys.argv[1], "Rfc9001Packets", "0x00000001") + "\n" + kotlin_object(sys.argv[2], "Rfc9369Packets", "0x6b3343cf")
    open(sys.argv[k + 1], "w").write(o); print("ok"); sys.exit(0)

out = sys.argv[3]
open(os.path.join(out, "vectors_rfc9001.h"), "w").write(extract(sys.argv[1], "RFC9001", "0x00000001u"))
open(os.path.join(out, "vectors_rfc9369.h"), "w").write(extract(sys.argv[2], "RFC9369", "0x6b3343cfu"))
print("ok")
