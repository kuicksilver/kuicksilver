# Generates the small PKI (100-year validity) of the kuicksilver-tls test of the bound that carried OpenSSL patch 11 sets
# (CVE-2026-121482, ADR-0019): a root, a server leaf it issued with 17 nameRelativeToCRLIssuer CRL distribution points (one
# more than upstream's MAX_DP_NAMES), its key, and a CRL of the root with an issuingDistributionPoint (fullName). Written as
# CrlDpCerts.kt for the kuicksilver-tls tests; the C tests build their own with OpenSSL's API (test_revocation.c). Kept apart
# from gen-revocation-certs.sh so that its PKI is not regenerated. Requires an OpenSSL 3.x or 4.x CLI. Usage: gen-crldp-certs.sh
set -euo pipefail
root="$(cd "$(dirname "$0")/../.." && pwd)"
kt="$root/kuicksilver-tls/src/commonTest/kotlin/io/kuicksilver/tls/CrlDpCerts.kt"
O="${OPENSSL:-$(command -v openssl)}"; "$O" version | grep -Eq '^OpenSSL [34]\.' || { echo "need an OpenSSL 3.x or 4.x CLI (set OPENSSL)"; exit 2; }
work=$(mktemp -d); trap 'rm -rf "$work"' EXIT INT TERM HUP; cd "$work"
DAYS=36500
"$O" ecparam -name prime256v1 -genkey -noout -out ca.key
"$O" req -x509 -new -key ca.key -out ca.pem -days $DAYS -sha256 -subj "/CN=Kuicksilver CRL DP Test Root" \
  -addext "basicConstraints=critical,CA:TRUE" -addext "keyUsage=critical,keyCertSign,cRLSign" 2>/dev/null
"$O" ecparam -name prime256v1 -genkey -noout -out leaf.key
"$O" req -new -key leaf.key -out leaf.csr -subj "/CN=crldp-leaf" 2>/dev/null
{
  printf 'basicConstraints=CA:FALSE\nkeyUsage=digitalSignature\nextendedKeyUsage=serverAuth\nsubjectAltName=DNS:server.test\n'
  printf 'crlDistributionPoints=%s\n' "$(for i in $(seq 0 16); do printf 'dp%d,' "$i"; done | sed 's/,$//')"
  for i in $(seq 0 16); do printf '[dp%d]\nrelativename=rdn%d\n[rdn%d]\nCN=dp%d\n' "$i" "$i" "$i" "$i"; done
} > leaf.ext
"$O" x509 -req -in leaf.csr -CA ca.pem -CAkey ca.key -CAcreateserial -sha256 -days $DAYS -out leaf.pem -extfile leaf.ext \
  2>/dev/null
[ "$("$O" x509 -in leaf.pem -noout -ext crlDistributionPoints | grep -c 'Relative Name')" = 17 ] \
  || { echo "the leaf does not carry 17 relative distribution points"; exit 1; }
: > index.txt; echo 01 > crlnumber
cat > ca.cnf <<'EOF'
[ ca ]
default_ca = root
[ root ]
database = index.txt
default_md = sha256
crlnumber = crlnumber
[ idp ]
issuingDistributionPoint = critical, @idp_dp
[ idp_dp ]
fullname = URI:http://crl.test/crldp.crl
EOF
"$O" ca -config ca.cnf -gencrl -keyfile ca.key -cert ca.pem -crldays $DAYS -crlexts idp -out root.crl 2>/dev/null
b64() { base64 < "$1" | tr -d '\n'; }
"$O" x509 -in ca.pem -outform DER -out root.der
"$O" x509 -in leaf.pem -outform DER -out leaf.der
"$O" pkcs8 -topk8 -nocrypt -in leaf.key -outform DER -out leaf.key.der
"$O" crl -in root.crl -outform DER -out root-crl.der
mkdir -p "$(dirname "$kt")"
{
  printf '// Copyright 2026 The Kuicksilver Authors\n// SPDX-License-Identifier: Apache-2.0\n// generated by tools/certs/gen-crldp-certs.sh — do not edit\n@file:Suppress("ktlint", "MaxLineLength")\n\npackage io.kuicksilver.tls\n\nimport kotlin.io.encoding.Base64\n\n'
  printf '/** A root, its leaf with 17 relative CRL distribution points and key, and its CRL with an issuingDistributionPoint. */\ninternal object CrlDpCerts {\n    private fun b64(s: String): ByteArray = Base64.decode(s)\n'
  printf '    val root: ByteArray by lazy { b64("%s") }\n' "$(b64 root.der)"
  printf '    val leaf17: ByteArray by lazy { b64("%s") }\n' "$(b64 leaf.der)"
  printf '    val leaf17Key: ByteArray by lazy { b64("%s") }\n' "$(b64 leaf.key.der)"
  printf '    val rootCrl: ByteArray by lazy { b64("%s") }\n' "$(b64 root-crl.der)"
  printf '}\n'
} > "$kt"
echo "generated $kt"
