# Generates the fixture of the JVM platform verifier's offline mode (RFC 9849 section 10.7): a CA and a leaf for server.test
# whose CRL distribution point and OCSP responder are http://127.0.0.1:1/ (a port nothing listens on), valid for a century,
# as OfflineTrustCerts.kt for the kuicksilver-tls JVM tests. A verifier that checks revocation must try those URLs and fail;
# one that stays offline never looks at them. Test certificates only. Usage: gen-offline-trust-certs.sh
set -euo pipefail
root="$(cd "$(dirname "$0")/../.." && pwd)"
kt="$root/kuicksilver-tls/src/jvmTest/kotlin/io/kuicksilver/tls/OfflineTrustCerts.kt"
O="${OPENSSL:-$(command -v openssl)}"
t=$(mktemp -d); trap 'rm -rf "$t"' EXIT
"$O" req -x509 -newkey ec -pkeyopt ec_paramgen_curve:P-256 -nodes -keyout "$t/ca.key" -out "$t/ca.pem" -days 36500 \
  -subj "/CN=Offline Trust Test CA" -addext "basicConstraints=critical,CA:TRUE" -addext "keyUsage=critical,keyCertSign,cRLSign" 2>/dev/null
"$O" req -new -newkey ec -pkeyopt ec_paramgen_curve:P-256 -nodes -keyout "$t/leaf.key" -out "$t/leaf.csr" -subj "/CN=server.test" 2>/dev/null
cat > "$t/ext" <<X
basicConstraints=critical,CA:FALSE
keyUsage=critical,digitalSignature
extendedKeyUsage=serverAuth
subjectAltName=DNS:server.test
crlDistributionPoints=URI:http://127.0.0.1:1/ca.crl
authorityInfoAccess=OCSP;URI:http://127.0.0.1:1/ocsp,caIssuers;URI:http://127.0.0.1:1/ca.cer
X
"$O" x509 -req -in "$t/leaf.csr" -CA "$t/ca.pem" -CAkey "$t/ca.key" -CAcreateserial -days 36500 -extfile "$t/ext" -out "$t/leaf.pem" 2>/dev/null
{
  printf '// Copyright 2026 The Kuicksilver Authors\n// SPDX-License-Identifier: Apache-2.0\n// generated by tools/certs/gen-offline-trust-certs.sh — do not edit\n@file:Suppress("ktlint", "MaxLineLength")\n\npackage io.kuicksilver.tls\n\n'
  printf '/** A CA and a leaf for server.test whose CRL and OCSP URLs are http://127.0.0.1:1/ (nothing listens there). */\ninternal object OfflineTrustCerts {\n'
  printf '    const val CA: String = """%s"""\n' "$(cat "$t/ca.pem")"
  printf '    const val LEAF: String = """%s"""\n' "$(cat "$t/leaf.pem")"
  printf '}\n'
} > "$kt"
echo "generated $kt"
