# Generates the Apple trust test PKI as AppleTrustCerts.kt (kuicksilver-tls appleTest): a root and a TLS server leaf of at most
# 825 days, the longest validity SecTrust accepts for a server certificate under any anchor (the 100-year leaves of
# gen-testcerts.sh fail it). The tests evaluate at a fixed date inside the leaf's validity, so the fixture does not expire.
# Requires a host openssl >= 3.0. Usage: gen-apple-trust-certs.sh
set -euo pipefail
root="$(cd "$(dirname "$0")/../.." && pwd)"
kt="$root/kuicksilver-tls/src/appleTest/kotlin/io/kuicksilver/tls/AppleTrustCerts.kt"
O="${OPENSSL:-$(command -v openssl)}"; "$O" version | grep -q 'OpenSSL 3' || { echo "need OpenSSL 3.x CLI"; exit 2; }
work=$(mktemp -d); trap 'rm -rf "$work"' EXIT INT TERM HUP; cd "$work"
"$O" req -x509 -newkey ec -pkeyopt ec_paramgen_curve:P-256 -nodes -keyout ca.key -out ca.pem -days 36500 -subj "/CN=Kuicksilver Apple Test Root" \
  -addext "basicConstraints=critical,CA:TRUE" -addext "keyUsage=critical,keyCertSign" 2>/dev/null
"$O" ecparam -name prime256v1 -genkey -noout -out leaf.key
"$O" req -new -key leaf.key -out leaf.csr -subj "/CN=server.test" 2>/dev/null
printf 'basicConstraints=CA:FALSE\nkeyUsage=critical,digitalSignature\nextendedKeyUsage=serverAuth\nsubjectAltName=DNS:server.test\n' > leaf.ext
"$O" x509 -req -in leaf.csr -CA ca.pem -CAkey ca.key -CAcreateserial -out leaf.pem -days 800 -extfile leaf.ext 2>/dev/null
nb=$("$O" x509 -in leaf.pem -noout -startdate | cut -d= -f2)
epoch=$(date -j -u -f '%b %e %T %Y %Z' "$nb" +%s 2>/dev/null || date -u -d "$nb" +%s)
b64() { "$O" x509 -in "$1" -outform DER | base64 | tr -d '\n'; }
{
  printf '// Copyright 2026 The Kuicksilver Authors\n// SPDX-License-Identifier: Apache-2.0\n// generated by tools/certs/gen-apple-trust-certs.sh — do not edit\n@file:Suppress("ktlint", "MaxLineLength")\n\npackage io.kuicksilver.tls\n\nimport kotlin.io.encoding.Base64\n\n'
  printf '/** A root and an 800-day `server.test` leaf that SecTrust accepts under that root; evaluate at [verifyAt]. */\ninternal object AppleTrustCerts {\n'
  printf '    val root: ByteArray by lazy { Base64.decode("%s") }\n' "$(b64 ca.pem)"
  printf '    val server: ByteArray by lazy { Base64.decode("%s") }\n' "$(b64 leaf.pem)"
  printf '\n    /** Seconds since 1970 inside the leaf'"'"'s validity (a day after its start). */\n    const val verifyAt: Long = %sL\n}\n' "$((epoch + 86400))"
} > "$kt"
