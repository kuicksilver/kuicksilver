# Generates HuffmanTable.kt (RFC 7541 Appendix B) and StaticTable.kt (RFC 9204 Appendix A) from the RFC texts.
# Usage: gen-qpack-tables.py [rfc7541.txt rfc9204.txt]   (downloads from rfc-editor.org when omitted). Run once; the output is committed.
import os, re, sys, urllib.request

root = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", ".."))
out_dir = os.path.join(root, "kuicksilver-http3/src/commonMain/kotlin/io/kuicksilver/http3/qpack")
HEADER = "// Copyright 2026 The Kuicksilver Authors\n// SPDX-License-Identifier: Apache-2.0\n// Generated by tools/http3/gen-qpack-tables.py from the RFC text; do not edit.\npackage io.kuicksilver.http3.qpack\n\n"

def text(arg, rfc):
    if arg: return open(arg, encoding="utf-8").read()
    return urllib.request.urlopen(f"https://www.rfc-editor.org/rfc/rfc{rfc}.txt").read().decode("utf-8")

def huffman(t):
    rows = re.findall(r"^\s+(?:'.'\s+)?\(\s*(\d+)\)\s+\|[01|]+\s+([0-9a-f]+)\s+\[\s*(\d+)\]", t, re.M)
    rows += [("256",) + m for m in re.findall(r"^\s+EOS \(256\)\s+\|[01|]+\s+([0-9a-f]+)\s+\[\s*(\d+)\]", t, re.M)]
    table = {int(s): (int(c, 16), int(l)) for s, c, l in rows}
    assert sorted(table) == list(range(257)), f"expected 257 symbols, got {len(table)}"
    codes = ", ".join(f"0x{table[i][0]:x}" for i in range(257))
    lens = ", ".join(str(table[i][1]) for i in range(257))
    return HEADER + "/** RFC 7541 Appendix B: code (LSB-aligned) and bit length of each symbol; 256 is EOS. */\ninternal object HuffmanTable {\n" \
        f"    val CODES: IntArray = intArrayOf({codes})\n    val LENGTHS: ByteArray = byteArrayOf({lens})\n}}\n"

def static_table(t):
    sec = t[t.index("Appendix A.  Static Table"):]
    sec = sec[sec.index("| Index"):]
    sec = sec[:sec.index("Appendix B")]
    entries, cur = [], None
    for line in sec.splitlines():
        if line.strip().startswith("+"):
            if cur and cur[0] != "Index": entries.append(cur)
            cur = None; continue
        m = re.match(r"^\s*\|\s*(\S*)\s*\|\s*(.*?)\s*\|\s*(.*?)\s*\|\s*$", line)
        if not m: continue
        idx, name, value = m.groups()
        if cur is None: cur = [idx, name, value]
        else:   # a wrapped cell continues on the next line
            if name: cur[1] += name
            if value: cur[2] += ("" if cur[2].endswith(("/", "-")) else " ") + value   # the RFC wraps after "/" and "-" without a space
    entries = [e for e in entries if e[0].isdigit()]
    assert [int(e[0]) for e in entries] == list(range(99)), [e[0] for e in entries]
    def q(s): return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'
    names = ",\n        ".join(q(e[1]) for e in entries); values = ",\n        ".join(q(e[2]) for e in entries)
    return HEADER + "/** RFC 9204 Appendix A: the 99 static table entries. */\ninternal object StaticTableData {\n" \
        f"    val NAMES: Array<String> = arrayOf(\n        {names},\n    )\n    val VALUES: Array<String> = arrayOf(\n        {values},\n    )\n}}\n"

a = sys.argv[1:3] + [None, None]
open(os.path.join(out_dir, "HuffmanTable.kt"), "w").write(huffman(text(a[0], 7541)))
open(os.path.join(out_dir, "StaticTableData.kt"), "w").write(static_table(text(a[1], 9204)))
print("generated HuffmanTable.kt (257 symbols) and StaticTableData.kt (99 entries)")
