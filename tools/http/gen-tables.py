# Generates the HPACK tables of kuicksilver-http2 from the RFC 7541 text: hpack/HuffmanTable.kt (appendix B, the same
# table QPACK uses) and hpack/StaticTableData.kt (appendix A, 61 entries); the shared test vectors
# tools/vectors/hpack-huffman.json (strings and their Huffman codes from appendix C.4 and C.6) and
# tools/vectors/hpack-rfc7541-appendix-c.json (every example of appendix C.2-C.6: field list, encoded block, dynamic
# table after it); and the Kotlin form of those vectors for the common tests, with the SHA-256 of the Huffman table.
# The Huffman table of kuicksilver-http3 (written by tools/http3/gen-qpack-tables.py, ADR-0017) must have the same body:
# --check compares every generated file, and that body, with what is committed and exits 1 on a difference.
# Usage: gen-tables.py [--check] [rfc7541.txt]   (downloads from rfc-editor.org when omitted). The output is committed.
import hashlib, json, os, re, sys, urllib.request

root = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", ".."))
H2_MAIN = os.path.join(root, "kuicksilver-http2/src/commonMain/kotlin/io/kuicksilver/http2/hpack")
H2_TEST = os.path.join(root, "kuicksilver-http2/src/commonTest/kotlin/io/kuicksilver/http2/hpack")
H3_HUFFMAN = os.path.join(root, "kuicksilver-http3/src/commonMain/kotlin/io/kuicksilver/http3/qpack/HuffmanTable.kt")
VECTORS = os.path.join(root, "tools/vectors")
GENERATED = "// Generated by tools/http/gen-tables.py from the RFC 7541 text; do not edit.\n"
SPDX = "// Copyright 2026 The Kuicksilver Authors\n// SPDX-License-Identifier: Apache-2.0\n"


def header(pkg):
    return SPDX + GENERATED + f"package {pkg}\n\n"


def kt_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def kt_array(kind, items, indent=8):
    pad = " " * indent
    return f"{pad}{kind}(\n" + "".join(f"{pad}    {i},\n" for i in items) + f"{pad})\n"


def huffman_table(t):
    rows = re.findall(r"^\s+(?:'.'\s+)?\(\s*(\d+)\)\s+\|[01|]+\s+([0-9a-f]+)\s+\[\s*(\d+)\]", t, re.M)
    rows += [("256",) + m for m in re.findall(r"^\s+EOS \(256\)\s+\|[01|]+\s+([0-9a-f]+)\s+\[\s*(\d+)\]", t, re.M)]
    table = {int(s): (int(c, 16), int(l)) for s, c, l in rows}
    assert sorted(table) == list(range(257)), f"expected 257 symbols, got {len(table)}"
    return [table[i][0] for i in range(257)], [table[i][1] for i in range(257)]


def huffman_body(codes, lengths):
    """The object as ktlint formats it: the part both modules share byte for byte."""
    return ("/** RFC 7541 Appendix B: code (LSB-aligned) and bit length of each symbol; 256 is EOS. */\n"
            "internal object HuffmanTable {\n    val CODES: IntArray =\n" + kt_array("intArrayOf", [f"0x{c:x}" for c in codes])
            + "    val LENGTHS: ByteArray =\n" + kt_array("byteArrayOf", [str(n) for n in lengths]) + "}\n")


def huffman_sha256(codes, lengths):
    """SHA-256 over each code as 4 big-endian bytes, then each length as one byte (HuffmanTableParityTest)."""
    return hashlib.sha256(b"".join(c.to_bytes(4, "big") for c in codes) + bytes(lengths)).hexdigest()


def static_table(t):
    sec = t[t.index("Appendix A.  Static Table Definition"):]
    sec = sec[sec.index("| Index"):sec.index("Appendix B.  Huffman Code")]
    entries = []
    for line in sec.splitlines():
        m = re.match(r"^\s*\|\s*(\d+)\s*\|\s*(\S+)\s*\|\s*(.*?)\s*\|\s*$", line)
        if m: entries.append((int(m.group(1)), m.group(2), m.group(3)))
    assert [e[0] for e in entries] == list(range(1, 62)), [e[0] for e in entries]
    assert entries[0][1] == ":authority" and entries[-1][1] == "www-authenticate"
    return [(n, v) for _, n, v in entries]


def huffman_encode(s, codes, lengths):
    acc, n, out = 0, 0, bytearray()
    for ch in s.encode("latin-1"):
        acc = (acc << lengths[ch]) | codes[ch]; n += lengths[ch]
        while n >= 8:
            n -= 8; out.append((acc >> n) & 0xff)
        acc &= (1 << n) - 1
    if n: out.append(((acc << (8 - n)) | ((1 << (8 - n)) - 1)) & 0xff)
    return bytes(out)


def strip_pages(text):
    """Drops the page footers and headers of the RFC text."""
    return re.sub(r"\n[^\n]*\[Page \d+\]\n\x0c?\n?RFC 7541[^\n]*\n", "\n", text)


def field_lines(block):
    """`name: value` lines (names may start with ':'), wrapped continuation lines joined with one space."""
    out = []
    for raw in block.splitlines():
        if not raw.strip(): continue
        if not raw.startswith(" "): break   # the next heading (C.3., C.4., ...)
        line = raw.strip()
        m = re.match(r"^(:?[^:\s]+): ?(.*)$", line)
        if m and raw.startswith("   ") and not raw.startswith("    "): out.append([m.group(1), m.group(2)])
        else: out[-1][1] += " " + line
    return out


def appendix_c(t, codes, lengths):
    t = strip_pages(t)
    sections = re.split(r"\n(C\.[2-6]\.\d)\.  [^\n]*\n", t[t.index("C.2.  Header Field Representation Examples"):t.rindex("Acknowledgments")])
    examples = []
    for i in range(1, len(sections), 2):
        sid, body = sections[i], sections[i + 1]
        fields = field_lines(body[body.index("Header list to encode:") + 22:body.index("Hex dump of encoded data:")])
        dump = body[body.index("Hex dump of encoded data:") + 25:body.index("Decoding process:")]
        encoded = bytes.fromhex("".join(line.split("|")[0].replace(" ", "") for line in dump.splitlines() if "|" in line))
        after = body[body.index("Decoding process:"):]
        table = []
        if "Dynamic Table (after decoding):" in after:
            tbl = after[after.index("Dynamic Table (after decoding):") + 31:after.index("Table size:")]
            for raw in tbl.splitlines():
                m = re.match(r"^\s*\[\s*(\d+)\]\s*\(s =\s*(\d+)\)\s*(:?[^:\s]+): ?(.*)$", raw)
                if m: table.append([m.group(3), m.group(4), int(m.group(2))])
                elif raw.strip(): table[-1][1] += " " + raw.strip()
            size = int(re.search(r"Table size:\s*(\d+)", after).group(1))
        else:
            size = 0
        for name, value, s in table:
            assert len(name) + len(value) + 32 == s, (sid, name, value, s)
        assert sum(s for _, _, s in table) == size, (sid, size)
        decoded = field_lines(after[after.index("Decoded header list:") + 20:])
        assert decoded == fields, (sid, decoded, fields)
        examples.append({"id": sid, "tableSize": 256 if sid[:3] in ("C.5", "C.6") else 4096,
                         "huffman": sid[:3] in ("C.4", "C.6"), "fields": fields, "encoded": encoded.hex(),
                         "table": [[n, v] for n, v, _ in table], "tableBytes": size})
    assert [e["id"] for e in examples] == ["C.2.1", "C.2.2", "C.2.3", "C.2.4"] + [f"C.{s}.{n}" for s in range(3, 7) for n in range(1, 4)]
    pairs = {}
    for e in examples:
        if not e["huffman"]: continue
        for n, v in e["fields"]:
            for s in (n, v):
                h = huffman_encode(s, codes, lengths)
                if len(h) < 127 and (bytes([0x80 | len(h)]) + h).hex() in e["encoded"]: pairs[s] = h.hex()
    assert len(pairs) >= 10, pairs
    return examples, [{"string": s, "huffman": h} for s, h in sorted(pairs.items())]


def vectors_kt(examples, pairs, sha):
    def strings(items, indent):
        pad = " " * indent
        if not items: return "listOf()"
        return f"listOf(\n" + "".join(f"{pad}    {kt_string(i)},\n" for i in items) + f"{pad})"
    def example(e):
        hexs = [e["encoded"][i:i + 64] for i in range(0, len(e["encoded"]), 64)]
        flat = lambda fs: [x for f in fs for x in f]
        args = [kt_string(e["id"]), str(e["tableSize"]), str(e["huffman"]).lower(), strings(hexs, 16), strings(flat(e["fields"]), 16),
                strings(flat(e["table"]), 16), str(e["tableBytes"])]
        return "            Example(\n" + "".join(f"                {a},\n" for a in args) + "            ),\n"
    hp = "".join(f"            {kt_string(p['string'])},\n            {kt_string(p['huffman'])},\n" for p in pairs)
    return (header("io.kuicksilver.http2.hpack")
            + "/** RFC 7541 appendix C (tools/vectors/hpack-rfc7541-appendix-c.json, tools/vectors/hpack-huffman.json) and the digest of appendix B. */\n"
            + "internal object Rfc7541Vectors {\n"
            + "    /** SHA-256 of [HuffmanTable.CODES] (4 big-endian bytes each) followed by [HuffmanTable.LENGTHS]. */\n"
            + f"    const val HUFFMAN_TABLE_SHA256: String = \"{sha}\"\n\n"
            + "    /**\n     * One example: its section, the table size it assumes, Huffman literals or not, the block (hex, in pieces), the fields and the\n"
            + "     * dynamic table after it (name, value, name, value, ...; newest entry first) and that table's size.\n     */\n"
            + "    class Example(\n        val id: String,\n        val tableSize: Int,\n        val huffman: Boolean,\n        val encodedHex: List<String>,\n"
            + "        val fields: List<String>,\n        val tableAfter: List<String>,\n        val tableBytes: Int,\n    )\n\n"
            + "    val EXAMPLES: List<Example> =\n        listOf(\n" + "".join(example(e) for e in examples) + "        )\n\n"
            + "    /** A string followed by its Huffman code (hex), each found in the encoded blocks of C.4 and C.6. */\n"
            + "    val HUFFMAN: List<String> =\n        listOf(\n" + hp + "        )\n}\n")


def main():
    args = [a for a in sys.argv[1:] if a != "--check"]
    check = "--check" in sys.argv[1:]
    text = open(args[0], encoding="utf-8").read() if args else urllib.request.urlopen("https://www.rfc-editor.org/rfc/rfc7541.txt").read().decode("utf-8")
    codes, lengths = huffman_table(text)
    statics = static_table(text)
    examples, pairs = appendix_c(text, codes, lengths)
    sha = huffman_sha256(codes, lengths)
    pkg = "io.kuicksilver.http2.hpack"
    out = {
        os.path.join(H2_MAIN, "HuffmanTable.kt"): header(pkg) + huffman_body(codes, lengths),
        os.path.join(H2_MAIN, "StaticTableData.kt"): header(pkg)
        + "/** RFC 7541 Appendix A: the 61 static table entries (index 1 is element 0). */\ninternal object StaticTableData {\n"
        + "    val NAMES: Array<String> =\n" + kt_array("arrayOf", [kt_string(n) for n, _ in statics])
        + "    val VALUES: Array<String> =\n" + kt_array("arrayOf", [kt_string(v) for _, v in statics]) + "}\n",
        os.path.join(H2_TEST, "Rfc7541Vectors.kt"): vectors_kt(examples, pairs, sha),
        os.path.join(VECTORS, "hpack-rfc7541-appendix-c.json"): json.dumps({"source": "RFC 7541 appendix C", "examples": examples}, indent=1) + "\n",
        os.path.join(VECTORS, "hpack-huffman.json"): json.dumps({"source": "RFC 7541 appendices B, C.4 and C.6", "sha256": sha, "pairs": pairs}, indent=1) + "\n",
    }
    bad = []
    for path, content in out.items():
        if check:
            if not os.path.exists(path) or open(path, encoding="utf-8").read() != content: bad.append(os.path.relpath(path, root))
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            open(path, "w", encoding="utf-8").write(content)
    h3 = open(H3_HUFFMAN, encoding="utf-8").read()
    if h3[h3.index("/** RFC 7541 Appendix B"):] != huffman_body(codes, lengths): bad.append(os.path.relpath(H3_HUFFMAN, root) + " (Huffman table body)")
    if bad:
        print("gen-tables: differs from the generator:\n  " + "\n  ".join(bad)); sys.exit(1)
    print(("checked" if check else "generated") + f" HuffmanTable.kt (257 symbols, sha256 {sha[:16]}…), StaticTableData.kt (61 entries), "
          f"{len(examples)} appendix C examples, {len(pairs)} Huffman pairs; kuicksilver-http3's Huffman table matches")


main()
