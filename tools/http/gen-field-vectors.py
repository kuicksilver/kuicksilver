# Writes the Kotlin form of tools/vectors/http-fields.json (the field and message rules HTTP/2 and HTTP/3 share: RFC 9113
# section 8, RFC 9114 section 4) into the common tests of kuicksilver-http2 (io.kuicksilver.http2.message) and
# kuicksilver-http3 (io.kuicksilver.http3.message), where each module's HttpFieldVectorsTest runs its own copy of the
# validator on every case (ADR-0017: copies under shared vectors, not a shared module).
# Usage: gen-field-vectors.py            writes both files
#        gen-field-vectors.py --check    exits 1 when a committed file differs from what the JSON gives (CI lint)
import json, os, sys

root = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", ".."))
SOURCE = os.path.join(root, "tools/vectors/http-fields.json")
TARGETS = {
    "io.kuicksilver.http2.message": os.path.join(root, "kuicksilver-http2/src/commonTest/kotlin/io/kuicksilver/http2/message/HttpFieldVectors.kt"),
    "io.kuicksilver.http3.message": os.path.join(root, "kuicksilver-http3/src/commonTest/kotlin/io/kuicksilver/http3/message/HttpFieldVectors.kt"),
}


def kt_string(s):
    out = []
    for c in s:
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif c == "$":
            out.append("\\$")
        elif ord(c) < 0x20 or ord(c) >= 0x7F:
            out.append("\\u%04x" % ord(c))
        else:
            out.append(c)
    return '"' + "".join(out) + '"'


def kt_bool(b):
    return "true" if b else "false"


def render(pkg, d):
    lines = [
        "// Copyright 2026 The Kuicksilver Authors",
        "// SPDX-License-Identifier: Apache-2.0",
        "// Generated by tools/http/gen-field-vectors.py from tools/vectors/http-fields.json; do not edit.",
        f"package {pkg}",
        "",
        "/** The field and message cases HTTP/2 and HTTP/3 share (tools/vectors/http-fields.json). */",
        "internal object HttpFieldVectors {",
        "    class Single(",
        "        val input: String,",
        "        val valid: Boolean,",
        "    )",
        "",
        "    class Authority(",
        "        val input: String,",
        "        val userinfo: Boolean,",
        "        val hostRequired: Boolean,",
        "        val portRequired: Boolean,",
        "        val valid: Boolean,",
        "    )",
        "",
        "    class Section(",
        "        val fields: List<Pair<String, String>>,",
        "        val valid: Boolean,",
        "    )",
        "",
    ]

    def singles(name, items):
        lines.append(f"    val {name}: List<Single> =")
        lines.append("        listOf(")
        for i in items:
            lines.append(f"            Single({kt_string(i['input'])}, {kt_bool(i['valid'])}),")
        lines.append("        )")
        lines.append("")

    def sections(name, items):
        lines.append(f"    val {name}: List<Section> =")
        lines.append("        listOf(")
        for i in items:
            if not i["fields"]:
                lines.append(f"            Section(listOf(), {kt_bool(i['valid'])}),")
                continue
            # one field per line: the form ktlint keeps, so formatKotlin never changes a generated file
            lines.append("            Section(")
            lines.append("                listOf(")
            for n, v in i["fields"]:
                lines.append(f"                    {kt_string(n)} to {kt_string(v)},")
            lines.append("                ),")
            lines.append(f"                {kt_bool(i['valid'])},")
            lines.append("            ),")
        lines.append("        )")
        lines.append("")

    singles("NAMES", d["names"])
    singles("VALUES", d["values"])
    lines.append("    val AUTHORITIES: List<Authority> =")
    lines.append("        listOf(")
    for a in d["authorities"]:
        lines.append(
            f"            Authority({kt_string(a['input'])}, {kt_bool(a['userinfo'])}, {kt_bool(a['hostRequired'])}, "
            f"{kt_bool(a['portRequired'])}, {kt_bool(a['valid'])}),"
        )
    lines.append("        )")
    lines.append("")
    sections("REQUESTS", d["requests"])
    sections("RESPONSES", d["responses"])
    sections("TRAILERS", d["trailers"])
    if lines[-1] == "":
        lines.pop()
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    check = "--check" in sys.argv[1:]
    with open(SOURCE, encoding="utf-8") as f:
        d = json.load(f)
    bad = []
    for pkg, path in TARGETS.items():
        text = render(pkg, d)
        if check:
            try:
                with open(path, encoding="utf-8") as f:
                    if f.read() != text:
                        bad.append(os.path.relpath(path, root))
            except FileNotFoundError:
                bad.append(os.path.relpath(path, root))
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)
    if bad:
        print("out of date (run tools/http/gen-field-vectors.py): " + ", ".join(bad))
        sys.exit(1)
    print("field vectors OK" if check else "wrote " + ", ".join(os.path.relpath(p, root) for p in TARGETS.values()))


if __name__ == "__main__":
    main()
